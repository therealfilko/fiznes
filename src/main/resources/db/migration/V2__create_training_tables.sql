CREATE TABLE muscle_groups
(
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    body_region_key TEXT NOT NULL
);

CREATE TABLE exercises
(
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT    NOT NULL,
    equipment BOOLEAN NOT NULL
);

CREATE TABLE exercise_muscle_groups
(
    exercise_id     INT,
    muscle_group_id INT,

    CONSTRAINT fk_exercise
        FOREIGN KEY (exercise_id)
            REFERENCES exercises (id),

    CONSTRAINT fk_muscle_group
        FOREIGN KEY (muscle_group_id)
            REFERENCES muscle_groups (id),

    PRIMARY KEY (exercise_id, muscle_group_id)
);

CREATE TABLE workouts
(
    id                        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      TEXT NOT NULL,
    default_work_seconds      INT DEFAULT 40,
    default_rest_seconds      INT DEFAULT 20,
    default_countdown_seconds INT DEFAULT 10
);

CREATE TABLE workout_exercises
(
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_id        INT NOT NULL,
    exercise_id       INT NOT NULL,
    work_seconds      INT,
    rest_seconds      INT,
    countdown_seconds INT,
    position          INT NOT NULL,

    CONSTRAINT fk_workout
        FOREIGN KEY (workout_id)
            REFERENCES workouts (id),

    CONSTRAINT fk_exercise
        FOREIGN KEY (exercise_id)
            REFERENCES exercises (id),

    CONSTRAINT unique_position UNIQUE (workout_id, position)
);