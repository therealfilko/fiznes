-- Prüfen ob Wert leer ist
SELECT impt.*
FROM impt
         LEFT JOIN exercises e ON e.name = impt.mu_key
         LEFT JOIN muscle_groups mu ON mu.body_region_key = impt.mu_key
WHERE e.id IS NULL OR mu.id IS NULL;

INSERT INTO exercise_muscle_groups(exercise_id, muscle_group_id, type)
SELECT e.id, mu.id, impt.type
FROM impt
         JOIN exercises e ON e.name = impt.e_name
         JOIN muscle_groups mu ON mu.body_region_key = impt.mu_key;